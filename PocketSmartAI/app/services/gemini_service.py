import json
from typing import Any

from google import genai
from google.genai import types
from pydantic import BaseModel

from app.config import settings
from app.models.schemas import (
    RecommendationItem,
    RecommendationResponse,
)
from app.services.catalog import (
    home_fallback,
    jewelry_fallback,
    party_fallback,
)


class GeminiRecommendation(BaseModel):
    title: str
    summary: str
    estimated_total: float
    allocation: dict[str, float]
    recommendations: list[RecommendationItem]
    tips: list[str]


SYSTEM = """
You are PocketSmart AI, a practical budget recommendation assistant.

Return only structured JSON matching the provided schema.

Never claim live prices or live inventory.
Use estimated prices in INR.

Keep estimated_total at or below the user's budget whenever possible.

Give concise, useful recommendations.

Every recommendation must contain:
name
category
platform
estimated_price
reason
link
quantity
"""


def _client():
    if not settings.gemini_api_key:
        return None

    return genai.Client(
        api_key=settings.gemini_api_key
    )


def _prompt(planner: str, payload: dict) -> str:
    return f"""
Planner: {planner}

User data:
{json.dumps(payload, ensure_ascii=False)}

Create a realistic budget-aware plan.

Return 5-8 recommendations when possible.

The estimated_total must not exceed the user's budget.

Prices are estimates in INR.

For each recommendation include:
- name
- category
- platform
- estimated_price
- reason
- link
- quantity
"""


def _fallback(planner: str, payload: BaseModel):

    budget = float(payload.budget)

    if planner == "home":

        recs = home_fallback(payload)

        allocation = {
            "furniture": budget * 0.45,
            "lighting": budget * 0.20,
            "decor": budget * 0.20,
            "buffer": budget * 0.15,
        }

        tips = [
            "Buy large furniture first, then fill decorative gaps.",
            "Keep 10-15% of the budget as a delivery and price-change buffer.",
        ]

        title = "Smart Home Interior Plan"

    elif planner == "party":

        recs = party_fallback(payload)

        allocation = {
            "food": budget * 0.45,
            "decoration": budget * 0.20,
            "venue": budget * 0.25,
            "buffer": budget * 0.10,
        }

        tips = [
            "Confirm food quantities based on the number of guests.",
            "Keep a small contingency amount for delivery and last-minute expenses.",
        ]

        title = "Smart Party Budget Plan"

    else:

        recs = jewelry_fallback(payload)

        allocation = {
            "necklace": budget * 0.45,
            "earrings": budget * 0.25,
            "bracelet": budget * 0.15,
            "buffer": budget * 0.15,
        }

        tips = [
            "Match the jewelry metal tone with the outfit.",
            "Keep some budget for delivery or alterations.",
        ]

        title = "Smart Jewelry Plan"

    total = 0.0

    for item in recs:

        if isinstance(item, BaseModel):
            item = item.model_dump()

        price = float(item.get("estimated_price", 0))
        quantity = int(item.get("quantity", 1))

        total += price * quantity

    total = min(total, budget)

    return {
        "title": title,
        "summary": (
            "A practical budget plan generated by PocketSmart AI."
        ),
        "estimated_total": round(total, 2),
        "allocation": {
            key: round(value, 2)
            for key, value in allocation.items()
        },
        "recommendations": recs,
        "tips": tips,
    }


def generate(
    planner: str,
    payload: BaseModel,
    image_bytes: bytes | None = None,
    image_mime: str | None = None,
) -> RecommendationResponse:

    raw = payload.model_dump()

    client = _client()

    result = None
    ai_generated = False

    # ---------------------------------------------------------
    # TRY GEMINI
    # ---------------------------------------------------------

    if client:

        try:

            contents: list[Any] = [
                _prompt(
                    planner,
                    raw,
                )
            ]

            # Jewelry image support
            if (
                image_bytes
                and image_mime
                and planner == "jewelry"
            ):

                contents.append(
                    types.Part.from_bytes(
                        data=image_bytes,
                        mime_type=image_mime,
                    )
                )

                contents.append(
                    """
                    Use the outfit image only as visual
                    context for jewelry color and style matching.
                    Do not identify the person.
                    """
                )

            response = client.models.generate_content(
                model=settings.gemini_model,
                contents=contents,
                config=types.GenerateContentConfig(
                    system_instruction=SYSTEM,
                    response_mime_type="application/json",
                    response_schema=GeminiRecommendation,
                    temperature=0.4,
                    max_output_tokens=5000,
                ),
            )

            if response and response.text:

                result = json.loads(
                    response.text
                )

                ai_generated = True

        except Exception as exc:

            # IMPORTANT:
            # Gemini failure must NOT crash the API.
            print(
                f"Gemini generation failed for {planner}: {exc}"
            )

            result = None
            ai_generated = False

    # ---------------------------------------------------------
    # FALLBACK
    # ---------------------------------------------------------

    if result is None:

        result = _fallback(
            planner,
            payload,
        )

        ai_generated = False

    # ---------------------------------------------------------
    # NORMALIZE RECOMMENDATIONS
    # ---------------------------------------------------------

    recommendations = result.get(
        "recommendations",
        [],
    )

    normalized = []

    for recommendation in recommendations:

        if isinstance(
            recommendation,
            BaseModel,
        ):

            recommendation = (
                recommendation.model_dump()
            )

        recommendation = dict(
            recommendation
        )

        recommendation.setdefault(
            "quantity",
            1,
        )

        recommendation.setdefault(
            "estimated_price",
            0,
        )

        recommendation.setdefault(
            "name",
            "Recommended item",
        )

        recommendation.setdefault(
            "category",
            planner,
        )

        recommendation.setdefault(
            "platform",
            "Online",
        )

        recommendation.setdefault(
            "reason",
            "Suitable for your budget and requirements.",
        )

        recommendation.setdefault(
            "link",
            "https://www.amazon.in/",
        )

        normalized.append(
            recommendation
        )

    # ---------------------------------------------------------
    # BUDGET
    # ---------------------------------------------------------

    budget = float(
        raw.get(
            "budget",
            0,
        )
    )

    estimated_total = float(
        result.get(
            "estimated_total",
            0,
        )
    )

    estimated_total = min(
        estimated_total,
        budget,
    )

    remaining = round(
        budget - estimated_total,
        2,
    )

    # ---------------------------------------------------------
    # FINAL RESPONSE
    # ---------------------------------------------------------

    return RecommendationResponse(

        planner=planner,

        title=result.get(
            "title",
            "PocketSmart AI Plan",
        ),

        summary=result.get(
            "summary",
            "Your budget plan has been generated.",
        ),

        budget=budget,

        estimated_total=estimated_total,

        remaining_budget=remaining,

        allocation=result.get(
            "allocation",
            {},
        ),

        recommendations=normalized,

        tips=result.get(
            "tips",
            [],
        ),

        ai_generated=ai_generated,

        model=(
            settings.gemini_model
            if ai_generated
            else None
        ),
    )